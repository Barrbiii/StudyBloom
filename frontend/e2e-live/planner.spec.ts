import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
test('реальный Docker: аккаунты, занятия, привычки, Pomodoro и подзадачи', async ({ page }, info) => {
  const password = `Live-${randomUUID()}`;
  const username = `live_${Date.now()}_${randomUUID().slice(0, 8)}`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Нет аккаунта? Зарегистрироваться', exact: true }).click();
  await page.getByLabel('Логин', { exact: true }).fill(username);
  await page.getByLabel('Пароль', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Создать аккаунт', exact: true }).click();
  await expect(page.getByRole('navigation')).toBeVisible();
  await page.getByLabel('Название задачи', { exact: true }).fill('Доклад интеграция');
  await page.getByRole('button', { name: 'Добавить +', exact: true }).click();
  await page.getByRole('button', { name: 'Шаги задачи: Доклад интеграция', exact: true }).click();
  await page.getByLabel('Новый шаг: Доклад интеграция').fill('Источники интеграция');
  await page.getByRole('button', { name: 'Добавить шаг', exact: true }).click();
  const step = page.getByRole('checkbox', { name: 'Источники интеграция', exact: true });
  await step.click(); await expect(step).toBeChecked();
  await page.getByLabel('Название предмета', { exact: true }).fill('Алгебра интеграция');
  await page.getByRole('button', { name: 'Добавить предмет', exact: true }).click();
  await expect(page.locator('.subject-chip')).toContainText('Алгебра интеграция');
  await page.getByRole('button', { name: 'Добавить занятие', exact: true }).click();
  const weekday = await page.evaluate(() => String((new Date().getDay() + 6) % 7));
  await page.getByRole('combobox', { name: 'День недели', exact: true }).selectOption(weekday);
  await page.getByLabel('Аудитория', { exact: true }).fill('210');
  await page.getByLabel('Преподаватель', { exact: true }).fill('Волков');
  await page.getByRole('button', { name: 'Сохранить занятие', exact: true }).click();
  await expect(page.locator('.calendar-lesson').first()).toContainText('Алгебра интеграция');
  const repeats=page.getByRole('region',{name:'Повторяющиеся задачи',exact:true});
  await repeats.getByLabel('Название повторения',{exact:true}).fill('Повторение интеграция');
  await repeats.getByRole('button',{name:'Создать шаблон',exact:true}).click();
  await repeats.getByRole('button',{name:'Создать задачи за период',exact:true}).click();
  await expect(repeats.getByRole('status')).toContainText('Создано задач: 1');
  await repeats.getByRole('button',{name:'Создать задачи за период',exact:true}).click();
  await expect(repeats.getByRole('status')).toContainText('Создано задач: 0');
  await page.getByRole('button', { name: 'Добавить привычку', exact: true }).click();
  await page.getByLabel('Название привычки', { exact: true }).fill('Повторить интеграция');
  await page.getByRole('button', { name: 'Сохранить привычку', exact: true }).click();
  await page.getByRole('button', { name: 'Выполнено', exact: true }).click();
  await expect(page.getByLabel('Цель выполнена', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Начать сессию', exact: true }).click();
  await page.getByRole('button', { name: 'Пауза', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Продолжить сессию', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button', { name: 'Продолжить сессию', exact: true })).toBeVisible();
  await expect(page.getByLabel('Цель выполнена', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Шаги задачи: Доклад интеграция', exact: true }).click();
  await expect(step).toBeChecked();
  await expect(page.locator('.insight-stats')).toContainText('1 / 1');
  const analytics=page.getByRole('region',{name:'Обзор и аналитика',exact:true});
  const today=await page.evaluate(()=>{const d=new Date();return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`;});
  await analytics.getByLabel('Аналитика с',{exact:true}).fill(today);
  await analytics.getByLabel('Аналитика по',{exact:true}).fill(today);
  await analytics.getByRole('button',{name:'Применить период',exact:true}).click();
  await expect(analytics.locator('.chart-day')).toHaveCount(1);
  const downloading=page.waitForEvent('download');
  await analytics.getByRole('button',{name:'Экспорт периода в CSV',exact:true}).click();
  const download=await downloading;
  expect(download.suggestedFilename()).toBe(`studybloom-focus-${today}-${today}.csv`);
  const path=await download.path();const csv=await readFile(path!,'utf8');
  expect(csv.split('\r\n').filter(Boolean)).toHaveLength(2);
  expect(csv).toContain(`"${today}",0,0,`);
  const archiveDownload=page.waitForEvent('download');
  await page.getByRole('button',{name:'Скачать личный архив JSON',exact:true}).click();
  const archiveFile=await archiveDownload;const archivePath=await archiveFile.path();
  const personal=JSON.parse(await readFile(archivePath!,'utf8'));
  expect(personal.data.tasks.some((t:any)=>t.title==='Доклад интеграция')).toBe(true);
  expect(personal.data.subtasks[0].completed).toBe(true);
  expect(personal.data.focus_sessions[0].state).toBe('paused');
  expect(personal.data.templates[0].title).toBe('Повторение интеграция');
  expect(JSON.stringify(personal)).not.toContain('password_hash');
  for (const width of [360, 390, 768]) {
    await page.setViewportSize({ width, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  await page.locator('#tasks').scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath('live-mobile.png') });
  await page.getByRole('button', { name: 'Выйти', exact: true }).click();
  await page.getByRole('button', { name: 'Нет аккаунта? Зарегистрироваться', exact: true }).click();
  await page.getByLabel('Логин', { exact: true }).fill(username + '_b');
  await page.getByLabel('Пароль', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Создать аккаунт', exact: true }).click();
  await expect(page.getByRole('navigation')).toBeVisible();
  await expect(page.locator('.task')).toHaveCount(0);
  await expect(page.locator('.calendar-lesson')).toHaveCount(0);
  await expect(page.locator('.habit-card')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Начать сессию', exact: true })).toBeEnabled();
  const secondArchive=await page.request.get('/api/export/study');
  expect(secondArchive.ok()).toBe(true);
  const secondData=(await secondArchive.json()).data;
  expect(Object.values(secondData).every((rows:any)=>rows.length===0)).toBe(true);
});
